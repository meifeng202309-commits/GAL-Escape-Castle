-- Scene transitions now persist permissions, timing starts and append-only
-- old/new context. Existing historical transitions are not synthesized.
create or replace function public.s3b_set_scene(
  p_run uuid,p_scene text,p_phase text,p_step text,p_mode text,p_text_key text
) returns void
language plpgsql security definer set search_path=public as $$
declare
  v_old public.s3_runtime_scene_state%rowtype;
  v_room text;
  v_allow_share boolean;
  v_had_old boolean;
begin
  if p_mode not in ('CINEMATIC_MESSAGE','CRITICAL_INFO','ACTION_SCREEN') then
    raise exception 'Invalid display mode.';
  end if;
  select * into v_old from public.s3_runtime_scene_state where run_id=p_run for update;
  v_had_old:=found;
  v_allow_share:=(p_scene='act2_first_contact' and p_phase='meeting_discussion')
    or (p_scene='act5_route_discussion' and p_phase='discussion');

  insert into public.s3_runtime_scene_state(
    run_id,scene_id,phase_key,step_key,display_mode,text_key,allow_share_photo
  ) values(p_run,p_scene,p_phase,p_step,p_mode,p_text_key,v_allow_share)
  on conflict(run_id) do update set
    scene_id=excluded.scene_id,phase_key=excluded.phase_key,step_key=excluded.step_key,
    display_mode=excluded.display_mode,text_key=excluded.text_key,
    allow_share_photo=excluded.allow_share_photo,updated_at=now();

  if p_scene='act2_first_contact' and p_phase='private_first_meeting' then
    update public.s3b_player_progress
    set first_meeting_started_at=coalesce(first_meeting_started_at,now()),
        first_meeting_timing_validity=case when first_meeting_started_at is null then 'valid' else first_meeting_timing_validity end
    where run_id=p_run and first_meeting_locked_at is null;
  elsif p_scene='act4_known_unknown' and p_phase='private_route_choice' then
    update public.s3b_player_progress
    set act4_choice_started_at=coalesce(act4_choice_started_at,now()),
        act4_timing_validity=case when act4_choice_started_at is null then 'valid' else act4_timing_validity end
    where run_id=p_run and act4_locked_at is null;
  end if;

  if not v_had_old or v_old.scene_id is distinct from p_scene
     or v_old.phase_key is distinct from p_phase
     or v_old.step_key is distinct from p_step then
    select room_code into v_room from public.game_runs where run_id=p_run;
    insert into public.runtime_events(
      run_id,room_code,event_type,details,scene_id,phase_key,step_key,
      event_source,validity,behavior_scoring
    ) values(
      p_run,v_room,'scene_transition',jsonb_build_object(
        'from_scene_id',v_old.scene_id,'from_phase_key',v_old.phase_key,
        'from_step_key',v_old.step_key,'to_scene_id',p_scene,
        'to_phase_key',p_phase,'to_step_key',p_step
      ),p_scene,p_phase,p_step,'server','valid',false
    );
  end if;
end;
$$;

