-- Refresh first, then validate the resulting locked prefix while holding the
-- same run-state lock. Request identity makes uncertain retries idempotent.
create or replace function public.s3b_submit_library_code(
  p_room_code text,p_session_token text,p_client_request_id uuid,p_code text
) returns jsonb language plpgsql security definer set search_path=public as $$
declare
  v_room text:=upper(trim(p_room_code));
  v_player public.s1_room_players%rowtype;
  v_run public.game_runs%rowtype;
  v_state public.s3b_run_state%rowtype;
  v_existing public.s3b_library_attempts%rowtype;
  v_n integer;
  v_hint integer;
  v_correct boolean;
begin
  if p_client_request_id is null then raise exception 'Puzzle request identity is required.'; end if;
  if p_code is null or p_code !~ '^[0-9]{5}$' then raise exception 'Library code must contain exactly five digits.'; end if;
  v_player:=public.s1_get_player_by_session(v_room,p_session_token);
  select * into v_run from public.game_runs where room_code=v_room and status='active' for update;
  if not found then raise exception 'No active formal run.'; end if;

  select * into v_existing from public.s3b_library_attempts
  where run_id=v_run.run_id and submitted_by=v_player.player_id
    and client_request_id=p_client_request_id;
  if found then
    if v_existing.submitted_value<>p_code then
      raise exception 'Puzzle request identity was reused with a different code.';
    end if;
    return jsonb_build_object(
      'ok',true,'correct',v_existing.correct,'attempt_number',v_existing.attempt_number,
      'client_request_id',p_client_request_id,'idempotent_replay',true
    );
  end if;

  if not exists(select 1 from public.s3_runtime_scene_state
    where run_id=v_run.run_id and scene_id='act3_library' and phase_key='library_box') then
    raise exception 'Library Box transition is unavailable.';
  end if;
  perform public.s3b_refresh_puzzle(v_run.run_id);
  select * into v_state from public.s3b_run_state where run_id=v_run.run_id for update;
  if not found or not v_state.party_physically_reunited or v_state.puzzle_resolved_at is not null then
    raise exception 'Library Box is not accepting attempts.';
  end if;
  if left(p_code,length(v_state.puzzle_locked_prefix))<>v_state.puzzle_locked_prefix then
    raise exception 'Locked puzzle wheels cannot be changed.';
  end if;

  v_correct:=p_code='41739';
  update public.s3b_run_state
  set puzzle_attempt_number=puzzle_attempt_number+1,
      puzzle_hint_stage=case when v_correct then puzzle_hint_stage else greatest(puzzle_hint_stage,least(puzzle_attempt_number+1,3)) end,
      puzzle_resolved_at=case when v_correct then now() else null end,
      updated_at=now()
  where run_id=v_run.run_id
  returning puzzle_attempt_number,puzzle_hint_stage into v_n,v_hint;

  insert into public.s3b_library_attempts(
    run_id,attempt_number,submitted_by,submitted_value,submitted_at,correct,client_request_id
  ) values(v_run.run_id,v_n,v_player.player_id,p_code,now(),v_correct,p_client_request_id);
  perform public.s3b_log_formal_event(
    v_run.run_id,'library_code_submitted',v_player.player_id,'player',
    jsonb_build_object('attempt_number',v_n,'correct',v_correct,'hint_stage',v_hint),
    'valid',false,null,p_client_request_id
  );

  if v_correct then
    insert into public.s3_group_items(run_id,item_key,label_text_key)
    values(v_run.run_id,'library_photo_1897','item.photo_1897'),
          (v_run.run_id,'library_torn_note','item.torn_note')
    on conflict do nothing;
    perform public.s3b_set_scene(v_run.run_id,'act4_known_unknown','private_route_choice','initial','ACTION_SCREEN','act04-05.002');
  else
    perform public.s2_log_event(
      v_run.run_id,v_room,null,'puzzle_hint_used',v_player.player_id,
      jsonb_build_object('attempt_number',v_n,'hint_stage',v_hint,'behavior_scoring',false,'client_request_id',p_client_request_id)
    );
  end if;
  return jsonb_build_object(
    'ok',true,'correct',v_correct,'attempt_number',v_n,'hint_stage',v_hint,
    'client_request_id',p_client_request_id,'idempotent_replay',false
  );
end;
$$;

-- Canonical three-player Game-only Step Vote for ACT5 post-inspection route.
create or replace function public.s3b_submit_post_inspection_route_vote(
  p_room_code text,p_session_token text,p_choice_id text
) returns jsonb language plpgsql security definer set search_path=public as $$
declare
  v_room text:=upper(trim(p_room_code));
  v_player public.s1_room_players%rowtype;
  v_run public.game_runs%rowtype;
  v_existing public.s3b_post_inspection_route_votes%rowtype;
  v_count integer;
  v_route text;
begin
  if p_choice_id not in ('known','unknown') then raise exception 'Post-inspection vote must be known or unknown.'; end if;
  v_player:=public.s1_get_player_by_session(v_room,p_session_token);
  select * into v_run from public.game_runs where room_code=v_room and status='active' for update;
  if not found then raise exception 'No active formal run.'; end if;
  perform 1 from public.s3b_run_state where run_id=v_run.run_id for update;

  select * into v_existing from public.s3b_post_inspection_route_votes
  where run_id=v_run.run_id and player_id=v_player.player_id;
  if found then
    if v_existing.choice_id<>p_choice_id then
      raise exception 'Post-inspection vote is already locked.';
    end if;
    select count(*) into v_count from public.s3b_post_inspection_route_votes where run_id=v_run.run_id;
    select group_route into v_route from public.s3b_run_state where run_id=v_run.run_id;
    return jsonb_build_object('ok',true,'submitted_count',v_count,'resolved',v_route is not null,'group_route',v_route,'idempotent_replay',true);
  end if;

  if not exists(select 1 from public.s3_runtime_scene_state
    where run_id=v_run.run_id and scene_id='act5_inspect_first' and phase_key='post_inspection_route')
    or not exists(select 1 from public.s3b_run_state
      where run_id=v_run.run_id and pending_post_inspection_route and group_route is null) then
    raise exception 'Post-inspection vote is unavailable.';
  end if;

  insert into public.s3b_post_inspection_route_votes(run_id,player_id,choice_id)
  values(v_run.run_id,v_player.player_id,p_choice_id);
  perform public.s3b_log_formal_event(
    v_run.run_id,'post_inspection_route_vote_locked',v_player.player_id,'player',
    jsonb_build_object('decision_type','game_only_step_vote'),
    'valid',false
  );
  select count(*) into v_count from public.s3b_post_inspection_route_votes where run_id=v_run.run_id;

  if v_count=3 then
    select choice_id into v_route
    from public.s3b_post_inspection_route_votes
    where run_id=v_run.run_id
    group by choice_id order by count(*) desc,choice_id limit 1;
    update public.s3b_run_state
    set group_route=v_route,pending_post_inspection_route=false,
        terminal_state='SPRINT3B_COMPLETE',updated_at=now()
    where run_id=v_run.run_id and pending_post_inspection_route and group_route is null;
    if not found then raise exception 'Post-inspection route was resolved concurrently.'; end if;
    perform public.s3b_log_formal_event(
      v_run.run_id,'post_inspection_route_resolved',null,'server',
      jsonb_build_object('group_route',v_route,'resolution_source','three_player_majority','submitted_count',3),
      'valid',false
    );
    perform public.s3b_set_scene(
      v_run.run_id,'act5_route_resolved','terminal',v_route,'CINEMATIC_MESSAGE',
      case v_route when 'known' then 'act04-05.019' else 'act04-05.024' end
    );
  end if;
  return jsonb_build_object('ok',true,'submitted_count',v_count,'resolved',v_count=3,'group_route',v_route,'idempotent_replay',false);
end;
$$;

-- SHARE PHOTO requires an authoritative allowed scene and an open canonical
-- discussion. Ownership/current-view/provenance checks remain unchanged.
create or replace function public.s3_share_photo(
  p_room_code text,p_session_token text,p_recipient_role text,
  p_source_item_key text,p_source_view text
) returns jsonb language plpgsql security definer set search_path=public as $$
declare
  v_room text:=upper(trim(p_room_code));
  v_sender public.s1_room_players%rowtype;
  v_recipient uuid;
  v_run public.game_runs%rowtype;
  v_scene public.s3_runtime_scene_state%rowtype;
  v_label text;
  v_current text;
  v_copy uuid;
begin
  v_sender:=public.s1_get_player_by_session(v_room,p_session_token);
  v_run:=public.s2_get_active_run(v_room);
  if v_run.run_id is null then raise exception 'No active formal run.'; end if;
  select * into v_scene from public.s3_runtime_scene_state where run_id=v_run.run_id for update;
  if not found or not v_scene.allow_share_photo then raise exception 'Photo sharing is unavailable in the current scene.'; end if;
  if not exists(select 1 from public.discussion_sessions
    where run_id=v_run.run_id and scene_id=v_scene.scene_id and status='discussion') then
    raise exception 'Photo sharing requires an open canonical discussion.';
  end if;
  if not exists(select 1 from public.s3_player_items
    where run_id=v_run.run_id and item_key=p_source_item_key and physical_owner_id=v_sender.player_id) then
    raise exception 'Sender is not the physical owner of this item.';
  end if;
  select current_view into v_current from public.s3_player_item_view_state
  where run_id=v_run.run_id and player_id=v_sender.player_id and item_key=p_source_item_key;
  if v_current is null then raise exception 'Item view state is not initialized.'; end if;
  if p_source_view<>v_current then raise exception 'Only the current server-authoritative item view can be shared.'; end if;
  select name_text_key into v_label from public.s3_item_catalog
  where item_key=p_source_item_key and shareable_views ? v_current;
  if v_label is null then raise exception 'Current item view is not shareable.'; end if;
  select player_id into v_recipient from public.s1_room_players
  where room_code=v_room and role_slot=upper(trim(p_recipient_role));
  if v_recipient is null or v_recipient=v_sender.player_id then raise exception 'Invalid photo recipient.'; end if;
  insert into public.s3_shared_photos(
    run_id,received_by,shared_by,source_item_key,source_view,label_text_key
  ) values(v_run.run_id,v_recipient,v_sender.player_id,p_source_item_key,v_current,v_label)
  on conflict(run_id,received_by,shared_by,source_item_key,source_view)
  do update set shared_at=public.s3_shared_photos.shared_at
  returning photo_copy_id into v_copy;
  perform public.s3b_log_formal_event(
    v_run.run_id,'photo_shared',v_sender.player_id,'player',
    jsonb_build_object('photo_copy_id',v_copy,'received_by',v_recipient,'source_item_key',p_source_item_key,'source_view',v_current),
    'valid',true
  );
  return jsonb_build_object('ok',true,'photo_copy_id',v_copy,'source_view',v_current);
end;
$$;

-- Return reconnectable timing and private Game-only vote state without
-- revealing other players' votes before the server resolves the route.
alter function public.s3b_get_player_state(text,text) rename to s3b_get_player_state_pre014;
revoke execute on function public.s3b_get_player_state_pre014(text,text)
  from public,anon,authenticated;

create or replace function public.s3b_get_player_state(p_room_code text,p_session_token text)
returns jsonb language plpgsql security definer set search_path=public as $$
declare
  v_room text:=upper(trim(p_room_code));
  v_player public.s1_room_players%rowtype;
  v_run public.game_runs%rowtype;
  v_base jsonb;
  v_my_vote jsonb;
  v_count integer:=0;
  v_revealed jsonb:='[]'::jsonb;
  v_route text;
begin
  v_player:=public.s1_get_player_by_session(v_room,p_session_token);
  v_run:=public.s2_get_active_run(v_room);
  v_base:=public.s3b_get_player_state_pre014(p_room_code,p_session_token);
  if v_run.run_id is null then return v_base; end if;
  select jsonb_build_object('choice_id',choice_id,'locked_at',locked_at)
  into v_my_vote from public.s3b_post_inspection_route_votes
  where run_id=v_run.run_id and player_id=v_player.player_id;
  select count(*) into v_count from public.s3b_post_inspection_route_votes where run_id=v_run.run_id;
  select group_route into v_route from public.s3b_run_state where run_id=v_run.run_id;
  if v_route is not null then
    select coalesce(jsonb_agg(jsonb_build_object(
      'role_slot',p.role_slot,'choice_id',v.choice_id,'locked_at',v.locked_at
    ) order by p.role_slot),'[]'::jsonb) into v_revealed
    from public.s3b_post_inspection_route_votes v
    join public.s1_room_players p on p.player_id=v.player_id
    where v.run_id=v_run.run_id;
  end if;
  return v_base || jsonb_build_object(
    'post_inspection_vote_count',v_count,
    'my_post_inspection_vote',v_my_vote,
    'post_inspection_votes_revealed',v_revealed
  );
end;
$$;

