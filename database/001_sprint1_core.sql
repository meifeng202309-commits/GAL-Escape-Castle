-- Sprint 1 core multiplayer migration for GAL Castle Escape.
-- Run this in the Supabase SQL editor before using index.html / teacher.html.
-- This migration is stricter than the Three Doors demo:
-- - no public table DELETE/reset
-- - browser code uses publishable key only
-- - students act through session-token RPC functions
-- - teacher actions require a room-specific teacher token
-- - private choices are hidden from teacher until reveal

create extension if not exists pgcrypto;

create table if not exists public.s1_rooms (
  room_code text primary key,
  teacher_token_hash text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.s1_room_players (
  player_id uuid primary key default gen_random_uuid(),
  room_code text not null references public.s1_rooms(room_code) on delete cascade,
  role_slot text not null check (role_slot in ('GAL-A','GAL-B','GAL-C')),
  display_name text not null,
  join_code_hash text not null,
  session_token_hash text,
  joined_at timestamptz,
  last_seen_at timestamptz,
  unique (room_code, role_slot)
);

do $$
begin
  if not exists (
    select 1
    from pg_constraint
    where conname = 's1_room_players_room_join_code_hash_unique'
      and conrelid = 'public.s1_room_players'::regclass
  ) then
    alter table public.s1_room_players
      add constraint s1_room_players_room_join_code_hash_unique unique (room_code, join_code_hash);
  end if;
end;
$$;

create table if not exists public.s1_scene_choices (
  scene_id integer not null,
  choice_id text not null,
  choice_label text not null,
  active boolean not null default true,
  primary key (scene_id, choice_id)
);

create table if not exists public.s1_room_state (
  room_code text primary key references public.s1_rooms(room_code) on delete cascade,
  current_scene integer not null default 1,
  phase text not null default 'collecting' check (phase in ('collecting','revealed','completed')),
  updated_at timestamptz not null default now()
);

create table if not exists public.s1_player_decisions (
  decision_id bigint generated by default as identity primary key,
  room_code text not null references public.s1_rooms(room_code) on delete cascade,
  scene_id integer not null,
  player_id uuid not null references public.s1_room_players(player_id) on delete cascade,
  decision_type text not null default 'private_choice',
  choice_id text not null,
  choice_label text not null,
  locked_at timestamptz not null default now(),
  unique (room_code, scene_id, player_id, decision_type)
);

create table if not exists public.s1_game_events (
  event_id bigint generated by default as identity primary key,
  room_code text not null references public.s1_rooms(room_code) on delete cascade,
  event_type text not null,
  actor_player_id uuid,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

alter table public.s1_rooms enable row level security;
alter table public.s1_room_players enable row level security;
alter table public.s1_scene_choices enable row level security;
alter table public.s1_room_state enable row level security;
alter table public.s1_player_decisions enable row level security;
alter table public.s1_game_events enable row level security;

